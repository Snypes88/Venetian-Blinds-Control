"""Turn the raw T1 ESPHome logs into tests/t1_traces.h: one trace per relay-on period.

Usage: python gen_t1_traces.py <folder with phase-run*.log> <output header>
"""
import glob
import os
import re
import sys

ANSI = re.compile(r"\x1b\[[0-9;]*m")
LINE = re.compile(r"\[(\d\d):(\d\d):(\d\d)\.(\d+)\]\[S\]\[(sensor|switch)\]: '([^']+)' >> (\S+)")


def to_ms(h, m, s, frac):
    return (int(h) * 3600 + int(m) * 60 + int(s)) * 1000 + int(frac[:3].ljust(3, "0"))


events = set()
for path in glob.glob(os.path.join(sys.argv[1], "phase-run*.log")):
    for raw in open(path, errors="ignore"):
        m = LINE.search(ANSI.sub("", raw))
        if not m:
            continue
        h, mi, s, frac, kind, name, value = m.groups()
        t = to_ms(h, mi, s, frac)
        channel = "UP" if "Up" in name else "DOWN"
        if kind == "switch" and "Motor" in name:
            events.add((t, 0, "relay", channel, value))
        elif kind == "sensor" and "Active Power" in name:
            events.add((t, 1, "power", channel, float(value)))

runs = []
active = {}
for t, _, what, channel, value in sorted(events):
    if what == "relay":
        if value == "ON" and channel not in active:
            active[channel] = {"channel": channel, "on": t, "samples": []}
        elif value == "OFF" and channel in active:
            run = active.pop(channel)
            run["relay_ms"] = t - run["on"]
            runs.append(run)
    elif channel in active:
        active[channel]["samples"].append((t - active[channel]["on"], value))

runs.sort(key=lambda r: r["on"])
with open(sys.argv[2], "w") as out:
    out.write("// Generated by gen_t1_traces.py from the 2026-09-05 kitchen-door logs.\n#pragma once\n")
    out.write("struct Sample { unsigned t_ms; float watts; };\n")
    out.write("struct Trace { const char *name; const char *channel; unsigned relay_ms; const Sample *samples; unsigned count; };\n")
    for i, run in enumerate(runs):
        body = ", ".join(f"{{{t}, {w}f}}" for t, w in run["samples"])
        out.write(f"static const Sample RUN{i}[] = {{{body}}};\n")
    out.write("static const Trace T1_TRACES[] = {\n")
    for i, run in enumerate(runs):
        on = run["on"] // 1000
        name = f"{on // 3600:02d}:{on // 60 % 60:02d}:{on % 60:02d}"
        out.write(f'  {{"{name}", "{run["channel"]}", {run["relay_ms"]}, RUN{i}, {len(run["samples"])}}},\n')
    out.write("};\n")
for run in runs:
    print(run["channel"], run["on"], run["relay_ms"], len(run["samples"]))
